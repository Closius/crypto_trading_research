def generate_graph(pairs):
    """
    for example pairs:
        [(1, 2), (5, 6), (12, 6), (21, 4), (88, 0), (12, 2), (2, 3), (88, 4)]
    return graph in dict:
        {0: [5, 6], 1: [2], 2: [5, 1], 3: [7], 4: [7], 5: [2, 0, 6], 6: [0, 5], 7: [4, 3]}
    """
    # Create a graph where each node is a pair and edges exist if two pairs share a common element
    graph = defaultdict(list)

    # Map each element to the pairs that contain it
    """
        https://docs.python.org/3/library/collections.html#defaultdict-examples
        
        s = [('yellow', 1), ('blue', 2), ('yellow', 3), ('blue', 4), ('red', 1)]
        d = defaultdict(list)
        for k, v in s:
            d[k].append(v)
        
        sorted(d.items())
        [('blue', [2, 4]), ('red', [1]), ('yellow', [1, 3])]
    """
    element_to_pairs = defaultdict(list)
    for idx, (a, b) in enumerate(pairs):
        element_to_pairs[a].append(idx)
        element_to_pairs[b].append(idx)

    # Build the graph by connecting pairs with a common element
    for idx, (a, b) in enumerate(pairs):
        for neighbor in element_to_pairs[a] + element_to_pairs[b]:
            if neighbor != idx:
                graph[idx].append(neighbor)

    return graph


def dfs_with_depth(graph, node, path=None, visited=None, all_paths=None, current_depth=0, max_depth=3):
    # Initialize path, visited set, and all_paths list if not already initialized
    if path is None:
        path = []
    if visited is None:
        visited = set()
    if all_paths is None:
        all_paths = []

    # Add the current node to the path and visited set
    path.append(node)
    visited.add(node)

    # If the current depth exceeds max depth, stop exploring further
    if current_depth == max_depth:
        all_paths.append(path.copy())
        return all_paths

    # Explore all unvisited neighbors recursively, increasing the depth
    for neighbor in graph[node]:
        if neighbor not in visited:
            dfs_with_depth(graph, neighbor, path.copy(), visited.copy(), all_paths, current_depth + 1, max_depth)

    return all_paths


def sequence_calculator(pairs_raw, start_coin, end_coin, max_depth):
    logger = mp_logging.LoggerWorker().getLogger(__name__)

    logger.info(f"number of pairs: {len(pairs_raw)}")
    logger.info(f"depth: {max_depth}")
    logger.info(f"start_coin: {start_coin}")
    logger.info(f"end_coin: {end_coin}")
    logger.info(f"-----")
    start_pairs = [x for x in pairs_raw if start_coin in x.split("/")]
    end_pairs = [x for x in pairs_raw if (end_coin in x.split("/")) and (x not in start_pairs)]
    # end_pairs should not contain start_pairs
    logger.info(f"start_pairs size: {len(start_pairs)}")
    logger.info(f"end_pairs size: {len(end_pairs)}")

    pairs = [x.split("/") for x in pairs_raw]

    gr = generate_graph(pairs)
    # print(gr)
    logger.info("graph generated")

    logger.info("generating seqs  ...")
    path_all = []
    for i, start_pair in enumerate(start_pairs):
        path_all += dfs_with_depth(gr, pairs_raw.index(start_pair), max_depth=max_depth - 1)
        # if i % 100 == 0:
        #     logger.info(f"\t{i+1} of {len(start_pairs)}")

    logger.info(f"number of sequence before filtration by end_coin: {len(path_all)}")
    logger.info(f"filtration by end_coin ...")

    path_all_fist = []
    uniq_pairs = set()
    for seq in path_all:
        if pairs_raw[seq[-1]] in end_pairs:
            path_all_fist.append(seq)
            for s in seq:
                uniq_pairs.add(pairs_raw[s])

    logger.info(f"======================================")
    logger.info(f"found seqs: {len(path_all_fist)}")
    logger.info(f"uniq pairs: {len(uniq_pairs)}")

    logger.info(f"first 5:")
    for i, p in enumerate(path_all_fist):
        logger.info(f"\t{[pairs_raw[x] for x in p]}")
        if i == 5:
            break


